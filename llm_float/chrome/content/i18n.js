var I18N_LANG = "zh";
function t(key) {
  var dict = I18N[I18N_LANG] || I18N.zh;
  return dict[key] || I18N.zh[key] || key;
}
function initI18n(cb) {
  try {
    chrome.storage.local.get({ language: "zh" }, (d) => {
      I18N_LANG = d.language || "zh";
      if (cb) cb();
    });
  } catch (e) { if (cb) cb(); }
}

